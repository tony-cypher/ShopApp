                ? Brand::where('slug', $row['brand'])->first()
                : null;

            Product::updateOrCreate(
                ['slug' => Str::slug($row['name'])],
                [
                    'category_id' => $category->id,
                    'brand_id' => $brand?->id,
                    'name' => $row['name'],
                    'description' => $row['description'],
                    'price' => $row['price'],
                    'compare_at_price' => $row['compare'] ?? null,
                    'emoji' => $row['emoji'],
                    'image_url' => '/img/products/'.Str::slug($row['name']).'.jpg',
