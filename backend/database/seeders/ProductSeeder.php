                    'featured' => $row['featured'] ?? false,
                    'is_deal' => $row['is_deal'] ?? false,
                    'rating' => $row['rating'],
                    'reviews_count' => $row['reviews'],
                    'rating_chips' => $row['chips'] ?? null,
                    'options' => $row['options'] ?? null,
                    'delivery_standard' => $row['standard'] ?? true,
                    'delivery_pickup' => $row['pickup'] ?? true,
